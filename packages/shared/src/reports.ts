import { isStaffRole, type UserRole } from './roles';

export const REPORT_CATEGORIES = [
  'pothole',
  'streetlight',
  'garbage',
  'water_leak',
  'sidewalk',
  'road',
  'public_infrastructure',
  'noise',
  'other',
] as const;
export type ReportCategory = (typeof REPORT_CATEGORIES)[number];

export const REPORT_STATUSES = [
  'submitted',
  'under_review',
  'assigned',
  'in_progress',
  'resolved',
  'closed',
  'rejected',
] as const;
export type ReportStatus = (typeof REPORT_STATUSES)[number];

export const REPORT_PRIORITIES = ['low', 'normal', 'high', 'urgent'] as const;
export type ReportPriority = (typeof REPORT_PRIORITIES)[number];

/**
 * Allowed status transitions. A report may only move along these edges.
 * `resolved` can be reopened to `in_progress` (e.g. a citizen disputes the fix);
 * `closed` and `rejected` are terminal.
 *
 * Mirrored by a database trigger in Phase 2 — the database is the source of truth.
 */
export const REPORT_STATUS_TRANSITIONS: Readonly<Record<ReportStatus, readonly ReportStatus[]>> = {
  submitted: ['under_review', 'assigned', 'rejected'],
  under_review: ['assigned', 'in_progress', 'rejected'],
  assigned: ['in_progress', 'under_review', 'rejected'],
  in_progress: ['resolved', 'assigned'],
  resolved: ['closed', 'in_progress'],
  closed: [],
  rejected: [],
};

export function isTerminalReportStatus(status: ReportStatus): boolean {
  return REPORT_STATUS_TRANSITIONS[status].length === 0;
}

export function getNextReportStatuses(status: ReportStatus): readonly ReportStatus[] {
  return REPORT_STATUS_TRANSITIONS[status];
}

/**
 * Whether `role` may move a report from `from` to `to`.
 * Only municipality staff can change statuses — a citizen can never mark
 * their own (or anyone's) report as resolved.
 */
export function canTransitionReportStatus(
  from: ReportStatus,
  to: ReportStatus,
  role: UserRole,
): boolean {
  if (!isStaffRole(role)) return false;
  return REPORT_STATUS_TRANSITIONS[from].includes(to);
}

/** Statuses that count as "open" for dashboards and duplicate detection. */
export const OPEN_REPORT_STATUSES = [
  'submitted',
  'under_review',
  'assigned',
  'in_progress',
] as const satisfies readonly ReportStatus[];

export function isOpenReportStatus(status: ReportStatus): boolean {
  return (OPEN_REPORT_STATUSES as readonly ReportStatus[]).includes(status);
}

/**
 * Tracking numbers are generated by the database (per-municipality sequence) and look like
 * `TLV-2026-000123`: municipality code (2–5 uppercase letters), year, 6-digit sequence.
 */
const TRACKING_NUMBER_PATTERN = /^[A-Z]{2,5}-\d{4}-\d{6}$/;

export function isValidTrackingNumber(value: string): boolean {
  return TRACKING_NUMBER_PATTERN.test(value);
}

export function normalizeTrackingNumber(value: string): string {
  return value.trim().toUpperCase();
}
